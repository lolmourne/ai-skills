#!/usr/bin/env node
// Regenerate `doc-lib.mjs` from the ByteCanvas source.
//
//   node sync-doc.mjs [--repo <path to bytecanvas checkout>]
//
// The document model, Markdown reader, `.bdoc` format, Word writer, page setup
// and style presets are bundled straight out of the app (`src/lib/doc/*`) with
// the esbuild in its node_modules, so what this skill writes is what the app
// writes rather than a port that drifts. Run this after any of those change,
// and check the app's preset count still matches SKILL.md.

import { existsSync, mkdtempSync, writeFileSync } from 'node:fs';
import { homedir, tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const args = process.argv.slice(2);
const ri = args.indexOf('--repo');
const repo = [ri >= 0 ? args[ri + 1] : null, process.env.BYTECANVAS_REPO, join(homedir(), 'Documents/projects/js/bytecanvas')]
	.filter(Boolean)
	.map((r) => resolve(r))
	.find((r) => existsSync(join(r, 'src/lib/doc/model.ts')));
if (!repo) {
	console.error('ByteCanvas checkout not found (pass --repo or set BYTECANVAS_REPO)');
	process.exit(2);
}
const esbuild = join(repo, 'node_modules/.bin/esbuild');
if (!existsSync(esbuild)) {
	console.error(`no esbuild in ${repo}/node_modules — run npm install there first`);
	process.exit(2);
}

const lib = join(repo, 'src/lib/doc');
const at = (f) => JSON.stringify(join(lib, f));
const entry = join(mkdtempSync(join(tmpdir(), 'bytedocs-')), 'entry.ts');
writeFileSync(
	entry,
	[
		`export * from ${at('model.ts')};`,
		`export { markdownToBlocks, blocksToMarkdown, parseInline, runsToMarkdown } from ${at('markdown.ts')};`,
		`export { packDoc, unpackDoc, DocFormatError, DOC_EXTENSION } from ${at('format.ts')};`,
		`export { buildDocx } from ${at('docx.ts')};`,
		`export { DEFAULT_SETUP, PAPERS, TEXT_WIDTHS, pageGeometry, printedSetup, sameSetup, sanitizeSetup } from ${at('page.ts')};`,
		`export { BAND_EDGE, bandToText, editBand, fillFields, hasBand, sanitizeBand, splitFields, textToBand } from ${at('bands.ts')};`,
		`export { DEFAULT_STYLES, PRESETS, ROLES, ROLE_LABELS, presetById, sanitizeStyles } from ${at('styles.ts')};`
	].join('\n')
);

const out = join(dirname(fileURLToPath(import.meta.url)), 'doc-lib.mjs');
const banner = `// GENERATED by sync-doc.mjs from ByteCanvas src/lib/doc — do not edit.\n// Regenerate: node ~/.claude/skills/bytedocs/scripts/sync-doc.mjs`;
const r = spawnSync(esbuild, [entry, '--bundle', '--format=esm', '--platform=neutral', '--target=es2022', `--banner:js=${banner}`, `--outfile=${out}`], { encoding: 'utf8' });
if (r.status !== 0) {
	console.error(r.stderr || r.stdout);
	process.exit(1);
}
const { PRESETS } = await import(`${out}?${Date.now()}`);
console.log(`wrote ${out} — ${PRESETS.length} presets`);
