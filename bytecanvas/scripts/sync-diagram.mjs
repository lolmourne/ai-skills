#!/usr/bin/env node
// Regenerate `diagram-lib.mjs` from the ByteCanvas source.
//
//   node sync-diagram.mjs [--repo <path to bytecanvas checkout>]
//
// The diagram shape library, anchor points and connector router are bundled
// straight out of the app (`src/lib/diagram/*`) with the esbuild in its
// node_modules, so the builder's shapes, anchors and routes are the app's own
// rather than a port that drifts. Run this after the app's shape library or
// routing changes, then rebuild any scene that uses diagrams.

import { existsSync, mkdtempSync, writeFileSync } from 'node:fs';
import { homedir, tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const args = process.argv.slice(2);
const ri = args.indexOf('--repo');
const repo = [ri >= 0 ? args[ri + 1] : null, process.env.BYTECANVAS_REPO, join(homedir(), 'Documents/projects/js/bytecanvas')]
	.filter(Boolean)
	.map((r) => resolve(r))
	.find((r) => existsSync(join(r, 'src/lib/diagram/library.ts')));
if (!repo) {
	console.error('ByteCanvas checkout not found (pass --repo or set BYTECANVAS_REPO)');
	process.exit(2);
}
const esbuild = join(repo, 'node_modules/.bin/esbuild');
if (!existsSync(esbuild)) {
	console.error(`no esbuild in ${repo}/node_modules — run npm install there first`);
	process.exit(2);
}

const lib = join(repo, 'src/lib/diagram');
const entry = join(mkdtempSync(join(tmpdir(), 'bcanvas-diagram-')), 'entry.ts');
writeFileSync(
	entry,
	[
		`export { SHAPE_LIBRARY, CATEGORIES, shapeDef, anchorsFor, labelPositionFor } from ${JSON.stringify(join(lib, 'library.ts'))};`,
		`export { routePoints, pointsToPath, arrowHead, anchorNormal } from ${JSON.stringify(join(lib, 'connector.ts'))};`,
		`export { pathBounds, pointAtT, ANCHOR_IDS } from ${JSON.stringify(join(lib, 'geometry.ts'))};`
	].join('\n')
);

const out = join(dirname(fileURLToPath(import.meta.url)), 'diagram-lib.mjs');
const banner = `// GENERATED by sync-diagram.mjs from ByteCanvas src/lib/diagram — do not edit.\n// Regenerate: node ~/.claude/skills/bytecanvas/scripts/sync-diagram.mjs`;
const r = spawnSync(esbuild, [entry, '--bundle', '--format=esm', '--platform=neutral', '--target=es2022', `--banner:js=${banner}`, `--outfile=${out}`], { encoding: 'utf8' });
if (r.status !== 0) {
	console.error(r.stderr || r.stdout);
	process.exit(1);
}
const { SHAPE_LIBRARY } = await import(`${out}?${Date.now()}`);
console.log(`wrote ${out} — ${SHAPE_LIBRARY.length} shapes`);
